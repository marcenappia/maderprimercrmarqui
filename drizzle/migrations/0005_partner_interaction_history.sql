-- Interaction history for partner relationship management (WhatsApp, calls, email, meetings).
CREATE TABLE public.partner_interactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id bigint NOT NULL REFERENCES public.partner_profiles(id) ON DELETE CASCADE,
  created_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  channel text NOT NULL DEFAULT 'WhatsApp' CHECK (channel IN ('WhatsApp','Ligação','E-mail','Reunião','Nota')),
  outcome text NOT NULL DEFAULT 'Contato realizado',
  summary text NOT NULL,
  response_summary text NOT NULL DEFAULT '',
  occurred_at timestamptz NOT NULL DEFAULT now(),
  next_contact_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX partner_interactions_owner_idx ON public.partner_interactions(created_by);
CREATE INDEX partner_interactions_partner_idx ON public.partner_interactions(partner_id);
ALTER TABLE public.partner_interactions ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.partner_interactions TO authenticated;
GRANT ALL ON public.partner_interactions TO service_role;
CREATE POLICY partner_interactions_owner_all ON public.partner_interactions
  FOR ALL TO authenticated
  USING (created_by = auth.uid() AND EXISTS (SELECT 1 FROM public.partner_profiles p WHERE p.id = partner_id AND p.created_by = auth.uid()))
  WITH CHECK (created_by = auth.uid() AND EXISTS (SELECT 1 FROM public.partner_profiles p WHERE p.id = partner_id AND p.created_by = auth.uid()));
ALTER PUBLICATION supabase_realtime ADD TABLE public.partner_interactions;
