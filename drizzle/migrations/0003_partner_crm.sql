-- MadePrimer CRM: partner pipeline, referrals, commissions and contracts.
-- All records are scoped to the authenticated creator; existing prospect data is untouched.
CREATE TABLE public.partner_profiles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name text NOT NULL,
  company_name text NOT NULL DEFAULT '',
  role text NOT NULL DEFAULT 'Arquiteto',
  phone text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  city text NOT NULL DEFAULT '',
  state text NOT NULL DEFAULT 'SP',
  specialties text NOT NULL DEFAULT '',
  source text NOT NULL DEFAULT 'Prospecção MadePrimer',
  relationship_status text NOT NULL DEFAULT 'Prospect',
  commission_rate numeric(5,2) NOT NULL DEFAULT 0.50 CHECK (commission_rate >= 0 AND commission_rate <= 100),
  next_contact_at timestamptz,
  notes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX partner_profiles_owner_idx ON public.partner_profiles(created_by);
CREATE INDEX partner_profiles_status_idx ON public.partner_profiles(relationship_status);

CREATE TABLE public.partner_projects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id bigint NOT NULL REFERENCES public.partner_profiles(id) ON DELETE CASCADE,
  created_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  project_name text NOT NULL,
  client_name text NOT NULL DEFAULT '',
  environment text NOT NULL DEFAULT '',
  city text NOT NULL DEFAULT '',
  estimated_value numeric(14,2) NOT NULL DEFAULT 0 CHECK (estimated_value >= 0),
  stage text NOT NULL DEFAULT 'Novo lead',
  expected_close_date date,
  notes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX partner_projects_owner_idx ON public.partner_projects(created_by);
CREATE INDEX partner_projects_partner_idx ON public.partner_projects(partner_id);

CREATE TABLE public.partner_referrals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referrer_partner_id bigint NOT NULL REFERENCES public.partner_profiles(id) ON DELETE CASCADE,
  referred_partner_id bigint NOT NULL REFERENCES public.partner_profiles(id) ON DELETE CASCADE,
  created_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'Indicada',
  commission_rate numeric(5,2) NOT NULL DEFAULT 0.50 CHECK (commission_rate >= 0 AND commission_rate <= 100),
  eligible_revenue numeric(14,2) NOT NULL DEFAULT 0 CHECK (eligible_revenue >= 0),
  commission_amount numeric(14,2) GENERATED ALWAYS AS (round(eligible_revenue * commission_rate / 100, 2)) STORED,
  commission_status text NOT NULL DEFAULT 'Pendente',
  notes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (referrer_partner_id <> referred_partner_id),
  UNIQUE (referrer_partner_id, referred_partner_id)
);
CREATE INDEX partner_referrals_owner_idx ON public.partner_referrals(created_by);

CREATE TABLE public.partner_contracts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partner_id bigint NOT NULL REFERENCES public.partner_profiles(id) ON DELETE CASCADE,
  created_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  title text NOT NULL,
  document_url text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'Rascunho',
  starts_on date,
  ends_on date,
  notes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX partner_contracts_owner_idx ON public.partner_contracts(created_by);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.partner_profiles, public.partner_projects, public.partner_referrals, public.partner_contracts TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
GRANT ALL ON public.partner_profiles, public.partner_projects, public.partner_referrals, public.partner_contracts TO service_role;

ALTER TABLE public.partner_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.partner_projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.partner_referrals ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.partner_contracts ENABLE ROW LEVEL SECURITY;

CREATE POLICY partner_profiles_owner_all ON public.partner_profiles FOR ALL TO authenticated USING (created_by = auth.uid()) WITH CHECK (created_by = auth.uid());
CREATE POLICY partner_projects_owner_all ON public.partner_projects FOR ALL TO authenticated USING (created_by = auth.uid() AND EXISTS (SELECT 1 FROM public.partner_profiles p WHERE p.id = partner_id AND p.created_by = auth.uid())) WITH CHECK (created_by = auth.uid() AND EXISTS (SELECT 1 FROM public.partner_profiles p WHERE p.id = partner_id AND p.created_by = auth.uid()));
CREATE POLICY partner_referrals_owner_all ON public.partner_referrals FOR ALL TO authenticated USING (created_by = auth.uid() AND EXISTS (SELECT 1 FROM public.partner_profiles p WHERE p.id = referrer_partner_id AND p.created_by = auth.uid()) AND EXISTS (SELECT 1 FROM public.partner_profiles p WHERE p.id = referred_partner_id AND p.created_by = auth.uid())) WITH CHECK (created_by = auth.uid() AND EXISTS (SELECT 1 FROM public.partner_profiles p WHERE p.id = referrer_partner_id AND p.created_by = auth.uid()) AND EXISTS (SELECT 1 FROM public.partner_profiles p WHERE p.id = referred_partner_id AND p.created_by = auth.uid()));
CREATE POLICY partner_contracts_owner_all ON public.partner_contracts FOR ALL TO authenticated USING (created_by = auth.uid() AND EXISTS (SELECT 1 FROM public.partner_profiles p WHERE p.id = partner_id AND p.created_by = auth.uid())) WITH CHECK (created_by = auth.uid() AND EXISTS (SELECT 1 FROM public.partner_profiles p WHERE p.id = partner_id AND p.created_by = auth.uid()));

