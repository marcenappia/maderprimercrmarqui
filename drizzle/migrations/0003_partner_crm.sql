ALTER PUBLICATION supabase_realtime ADD TABLE public.partner_projects;
ALTER PUBLICATION supabase_realtime ADD TABLE public.partner_referrals;
ALTER PUBLICATION supabase_realtime ADD TABLE public.partner_contracts;
